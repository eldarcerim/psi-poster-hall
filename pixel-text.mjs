export const pixelWidth=(text,scale=2)=>Math.max(0,Array.from(text).length*6*scale-scale);
export function pixelText(ctx,text,x,y,{scale=2,color='#283849',align='center'}={}){
 const chars=Array.from(text.toUpperCase());if(align==='center')x-=pixelWidth(text,scale)/2;
 ctx.fillStyle=color;
 for(const char of chars){
  const normal=char==='Đ'?'D':char.normalize('NFD')[0],rows=GLYPHS[normal]||GLYPHS['?'];
  for(let row=0;row<7;row++)for(let col=0;col<5;col++)if(rows[row][col]==='1')ctx.fillRect(Math.round(x+col*scale),Math.round(y+row*scale),scale,scale);
  if('ČŠŽ'.includes(char)){ctx.fillRect(Math.round(x+scale),Math.round(y-3*scale),scale,scale);ctx.fillRect(Math.round(x+2*scale),Math.round(y-2*scale),scale,scale);ctx.fillRect(Math.round(x+3*scale),Math.round(y-3*scale),scale,scale);}
  if(char==='Ć'){ctx.fillRect(Math.round(x+3*scale),Math.round(y-3*scale),scale,scale);ctx.fillRect(Math.round(x+2*scale),Math.round(y-2*scale),scale,scale);}
  if(char==='Đ')ctx.fillRect(Math.round(x-scale),Math.round(y+3*scale),4*scale,scale);
  x+=6*scale;
 }
}
export function labelLines(text,columns=16,maxLines=2){
 const words=text.trim().split(/\s+/),lines=[];let line='';
 for(const word of words){if((line+' '+word).trim().length>columns){if(line)lines.push(line);line=word;}else line=(line+' '+word).trim();}
 if(line)lines.push(line);return lines.slice(0,maxLines).map((s,i)=>s.length>columns||i===maxLines-1&&lines.length>maxLines?s.slice(0,columns-2)+'..':s);
}
